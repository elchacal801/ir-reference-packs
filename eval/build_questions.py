"""Resolve eval/questions.spec.yaml into eval/questions.yaml.

Each evidence alternative gets a verbatim quote (the element's text, or the matching table row) and its source
locators, read from the built canonical documents. Fails if an element or table row is missing, so evidence IDs
cannot silently drift. A spec with ``quotes: withhold_unredistributable`` records only the SHA-256 of quotes from
elements not cleared for redistribution, so the tracked question file carries no such text.

    uv run python eval/build_questions.py
"""
from __future__ import annotations

import json
import pathlib
import sys
from pathlib import Path

import yaml

from irpacks.evaluate import evidence_quote
from irpacks.util import sha256_text

ROOT = pathlib.Path(__file__).resolve().parents[1]


def load_docs(packs=("dynamic-ir", "nist-sp800-61r3")) -> dict:
    out = {}
    for pack in packs:
        doc = json.loads((ROOT / "build" / "local" / pack / "document.json").read_text(encoding="utf-8"))
        out[pack] = {"doc": doc, "els": {e["id"]: e for e in doc["elements"]}}
    return out


def resolve(alt: dict, docs: dict, withhold: bool = False) -> dict:
    d = docs[alt["pack"]]
    el = d["els"].get(alt["element_id"])
    if el is None:
        raise SystemExit(f"unknown element {alt['pack']}:{alt['element_id']}")
    spans = el["source_spans"]
    try:
        quote = evidence_quote(el, alt.get("native_locator"))
    except KeyError as exc:
        raise SystemExit(str(exc).strip("'\""))
    if alt.get("native_locator"):
        spans = next(r for r in el["attrs"]["rows"] if r.get("native_locator") == alt["native_locator"])["source_spans"]
    state = el["rights"]["state"]
    q = {"quote": quote}
    if withhold and state != "redistributable":
        q = {"quote": None, "quote_sha256": sha256_text(quote), "quote_withheld": f"source text not cleared ({state})"}
    return {**alt, "type": el["type"], **q, "mapping_status": el["mapping_status"], "rights_state": state,
            "locators": [{"pdf_page": s.get("page"), "page_label": s.get("page_label"), **({"url": s["url"]} if s.get("url") else {})}
                         for s in spans]}


def main(argv: list[str] | None = None) -> int:
    """Default: the original 25-question set. ``--spec X.spec.yaml`` resolves another set to ``X.yaml`` (no fixed
    composition; it must list its own packs)."""
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", default=str(ROOT / "eval" / "questions.spec.yaml"))
    a = ap.parse_args(argv)
    spec_path = Path(a.spec)
    spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
    main_set = spec_path.name == "questions.spec.yaml"
    docs = load_docs(tuple(spec.get("packs", ("dynamic-ir", "nist-sp800-61r3"))))
    out = {"schema_version": 1, "verified_by": spec["verified_by"], "verified_date": spec["verified_date"],
           "sources": {p: {"document_id": d["doc"]["document_id"], "source_sha256": d["doc"]["sources"]["authoritative"]["sha256"]}
                       for p, d in docs.items()},
           "questions": []}
    for q in spec["questions"]:
        q2 = dict(q)
        q2.setdefault("answerable", True)
        q2.setdefault("requires_context", False)
        q2.setdefault("needs_visual", False)
        withhold = spec.get("quotes") == "withhold_unredistributable"
        q2["evidence"] = [[resolve(a, docs, withhold) for a in group] for group in q.get("evidence", [])]
        if q2["answerable"] and not q2["evidence"]:
            raise SystemExit(f"{q['id']}: answerable question without evidence")
        out["questions"].append(q2)
    splits = {s: sum(1 for q in out["questions"] if q["split"] == s) for s in sorted({q["split"] for q in out["questions"]})}
    unans = sum(1 for q in out["questions"] if not q["answerable"])
    if main_set and (splits != {"heldout": 10, "tuning": 15} or unans < 3):
        raise SystemExit(f"bad composition: {splits}, unanswerable={unans}")
    out_path = spec_path.with_name(spec_path.name.replace(".spec.yaml", ".yaml"))
    out_path.write_text(
        "# GENERATED by eval/build_questions.py from questions.spec.yaml — do not edit by hand.\n"
        + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
    print(f"wrote {out_path.resolve().relative_to(ROOT)}: {splits}, unanswerable={unans}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
